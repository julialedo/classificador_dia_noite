"""Nessa parte, definimos o modelo a partir da base pré-treinada:"""

def cria_model():
    base_model = MobileNetV2(weights='imagenet', include_top=False, input_shape=(224, 224, 3)) # top false: cortamos a parte final de classificação da rede, que classifica 1000 objetos diferentes. input_shape: define o tamanho da imagem, e o 3 representa as cores RGB
    base_model.trainable = False # Só treina a parte nova sendo adicionada
    model = models.Sequential([
        base_model,
        layers.GlobalAveragePooling2D(), # A saída da base é um mapa de características bem complexo. Aqui é simplificado em um vetor numérico, pegando a média de cada característica
        layers.Dropout(0.3), # Durante o treino, 30% dos neurônios são desligados aleatoriamente a cada rodada para forçar a rede a não depender de um único caminho e a ser mais robusta
        layers.Dense(1, activation='sigmoid') # Sigmoid (saida é um valor entre 0 e 1) para classificação binária
    ])

    model.compile(optimizer=optimizers.Adam(learning_rate=1e-4), # Algoritmo que ajusta os pesos. O learning rate é um passo extremamente cauteloso
                  loss='binary_crossentropy', # Penaliza o modelo se ele estiver muito confiante em uma resposta errada
                  metrics=['accuracy', tf.keras.metrics.AUC(name='auc')]) # AUC mede o quão bem o modelo separa as duas classes
    return model

